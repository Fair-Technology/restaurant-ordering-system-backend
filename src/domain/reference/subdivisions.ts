/** The divisions for a country, or null when the country has none (state optional there). */
export function subdivisionsForCountry(
  countryCode: string | undefined | null,
): readonly Subdivision[] | null {
  const key = (countryCode ?? '').trim().toUpperCase();
  if (!key || !Object.prototype.hasOwnProperty.call(COUNTRY_SUBDIVISIONS, key)) return null;
  return COUNTRY_SUBDIVISIONS[key];
}

export function countryRequiresState(countryCode: string | undefined | null): boolean {
  return subdivisionsForCountry(countryCode) !== null;
}

function normalise(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\./g, '')
    .replace(/[-\s]+/g, ' ')
    .trim();
}

/**
 * True when `state` matches a division's code OR name for the country, ignoring case,
 * surrounding whitespace, diacritics, dots and extra spaces. When the country has no
 * list, any value is accepted.
 */
export function isKnownState(
  state: string | undefined | null,
  countryCode: string | undefined | null,
): boolean {
  const list = subdivisionsForCountry(countryCode);
  if (!list) return true;
  const wanted = normalise(state ?? '');
  if (!wanted) return false;
  return list.some((s) => normalise(s.code) === wanted || normalise(s.name) === wanted);
}
